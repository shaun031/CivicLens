@dataclass(frozen=True)
class LabeledPair:
    id: str
    group: str
    split: str
    label: str
    first: MatchInput
    second: MatchInput
    images: str


def dataset() -> list[LabeledPair]:
    pairs = []
    for group, split, label, a, b, left, right, distance, images, status in SCENARIOS:
        for variant in range(6):
            identity = f"synthetic-v1/{group}/{variant}"
            first = MatchInput(
                str(uuid5(NAMESPACE_URL, identity + "/a")),
                Category(a),
                12.97,
                77.59,
                TextRecord(left, left),
            )
            # Controlled position/noise variants within a scenario, never across splits.
            text = right.upper() if variant % 2 else "  ".join(right.split())
            second = MatchInput(
                str(uuid5(NAMESPACE_URL, identity + "/b")),
                Category(b),
                12.97 + (distance + variant * 0.15) / 111195.08,
                77.59,
                TextRecord(text, text),
                status,
            )
            pairs.append(LabeledPair(identity, group, split, label, first, second, images))
    return pairs
